/* test_constants.c - the constant census.
 *
 * Every PUFO_* value below is a value some other suite asserts AGAINST. As long as the test
 * spells the expectation with the same macro the code under test reads, moving the macro moves
 * the expectation and nothing fails -- the hole Part 95 and Part 96's mutation sweeps found
 * (124 -> 125 in a text stride, twice more in unit 96). This suite is the fix in one place:
 * each constant is pinned to a LITERAL here, so a silent change in src/ turns this gate red even
 * in the suites that keep using the macro. The literal is evidence, not a copy of the header:
 * the header comment beside each define carries the IDB address the value came from, and this
 * file names the header it read. Adding a shared constant a test asserts against means adding
 * its row here too.
 */
