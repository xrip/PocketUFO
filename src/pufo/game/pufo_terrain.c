/* Every template dimension in the builder is turned from cells into tiles by _rt_sdiv(byte, 10). */
static i32 Terrain_Tiles(u8 nCells)
{
    return (i32)nCells / PUFO_CELLS_PER_TILE;
}

typedef struct TerrainGrid {
    MapCell **apCells;
    i32       nDimX; /* tiles */
    i32       nDimY;
} TerrainGrid;

/* The original indexes Map + 0x15338 + 4*(60*nY + nX) + 0x3840*nLayer with no bounds test at all. */
static MapCell *Terrain_LookupCell(i32 nX, i32 nY, i32 nLayer, void *pUser)
{
    const TerrainGrid *pGrid = (const TerrainGrid *)pUser;

    if (nLayer < 0 || nLayer >= PUFO_TERRAIN_LAYER_COUNT) {
        return NULL;
    }
    if (nX < 0 || nY < 0) {
        return NULL;
    }
    if (nX >= PUFO_CELLS_PER_TILE * pGrid->nDimX || nY >= PUFO_CELLS_PER_TILE * pGrid->nDimY) {
        return NULL;
    }
    return pGrid->apCells[PUFO_TERRAIN_CELLS_PER_LAYER * nLayer
                          + PUFO_MAP_CELL_DIM * nY + nX];
}

typedef struct TerrainSprites {
    PufoFont *pFont;
    u16       nBase; /* Font_GetFlagSprBase(pFont, pTpl->nFlag) */
} TerrainSprites;

/* Map_ApplyTemplateToCells resolves a slot as Font_GetSprByIndex(fontSys, base + value - 2). */
static Mc1Rec *Terrain_GetSlotSprite(u8 nSlotValue, void *pUser)
{
    const TerrainSprites *pSpr = (const TerrainSprites *)pUser;

    return Font_GetSprByIndex(pSpr->pFont, (u16)(pSpr->nBase + nSlotValue - 2u));
}

static void Terrain_ApplyTemplate(const MapTerrainEnv *pEnv, const MapTemplate *pTpl,
                                  i32 nTileX, i32 nTileY)
{
    TerrainGrid     grid = { pEnv->apCells, *pEnv->pnMapDimX, *pEnv->pnMapDimY };
    TerrainSprites   spr = { pEnv->pFont, Font_GetFlagSprBase(pEnv->pFont, pTpl->nFlag) };

    MapTemplate_ApplyToCells(pTpl, Terrain_LookupCell, &grid, nTileX, nTileY,
                             Terrain_GetSlotSprite, &spr);
}

/* The .rmp reload that follows every module: nSizeX is header byte 1 / 10 and nSizeY is header
 * byte 0 / 10, which is the clearest independent proof of the .ma1 header direction. */
static void Terrain_LoadModuleRmp(const MapTerrainEnv *pEnv, const MapTemplate *pTpl,
                                  const char *pszName, i32 nTileX, i32 nTileY)
{
    Rmp_Load(pEnv->pRmp, pszName, nTileX, nTileY,
             Terrain_Tiles(MapTemplate_GetHeaderByte1(pTpl)),
             Terrain_Tiles(MapTemplate_GetHeaderByte0(pTpl)),
             MapTemplate_GetLevelCount(pTpl), *pEnv->pnMapDimX, *pEnv->pnMapDimY);
}

static bool Terrain_FootprintFits(const MapTemplate *pTpl, i32 nTileX, i32 nTileY,
                                  i32 nDimX, i32 nDimY)
{
    return nTileX + Terrain_Tiles(MapTemplate_GetHeaderByte1(pTpl)) <= nDimX
        && nTileY + Terrain_Tiles(MapTemplate_GetHeaderByte0(pTpl)) <= nDimY;
}

static bool Terrain_FootprintBusy(const u8 *paGrid, const MapTemplate *pTpl,
                                  i32 nTileX, i32 nTileY)
{
    i32 nW = Terrain_Tiles(MapTemplate_GetHeaderByte1(pTpl));
    i32 nH = Terrain_Tiles(MapTemplate_GetHeaderByte0(pTpl));
    i32 nRow;
    i32 nCol;

    for (nRow = nTileY; nRow < nTileY + nH; ++nRow) {
        for (nCol = nTileX; nCol < nTileX + nW; ++nCol) {
            if (paGrid[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol] != 0) {
                return true;
            }
        }
    }
    return false;
}

static void Terrain_StampGrid(u8 *paGrid, const MapTemplate *pTpl,
                              i32 nTileX, i32 nTileY, u8 nValue)
{
    i32 nW = Terrain_Tiles(MapTemplate_GetHeaderByte1(pTpl));
    i32 nH = Terrain_Tiles(MapTemplate_GetHeaderByte0(pTpl));
    i32 nRow;
    i32 nCol;

    for (nRow = nTileY; nRow < nTileY + nH; ++nRow) {
        for (nCol = nTileX; nCol < nTileX + nW; ++nCol) {
            paGrid[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol] = nValue;
        }
    }
}

/* "<terrain name for this mission type><suffix>", the base name every terrain module load starts
 * from. The original copies the nine-byte name byte by byte until its NUL and then strcat's. */
static void Terrain_TerrainName(char *pszOut, size_t cchOut, u8 nMissionType)
{
    pufo_strcpy(pszOut, g_aTerrainNameByMission[nMissionType]);
    pufo_strcat(pszOut, g_aTerrainNameSuffix[nMissionType], cchOut);
}

static void Terrain_ModuleName(char *pszOut, size_t cchOut, u8 nMissionType, i32 nModule)
{
    char szNum[16];

    pufo_strcpy(pszOut, g_aTerrainNameByMission[nMissionType]);
    snprintf(szNum, sizeof szNum, "%d", nModule);
    pufo_strcat(pszOut, szNum, cchOut);
}

static const char *Terrain_UfoName(u8 nVariant, i32 nTier)
{
    i32 nSlot = 3 * ((i32)nVariant - 1) + nTier;

    if (nSlot < 0 || nSlot >= (i32)(sizeof(g_aUfoModuleName) / sizeof(g_aUfoModuleName[0]))) {
        return ""; /* deviation: the original reads past the table; an empty name fails the load */
    }
    return g_aUfoModuleName[nSlot];
}

static const char *Terrain_PlaneName(u8 nMissionType)
{
    i32 nSlot = (i32)nMissionType - 1;

    if (nSlot < 0 || nSlot >= (i32)(sizeof(g_aPlaneName) / sizeof(g_aPlaneName[0]))) {
        return ""; /* deviation: mission type 0 makes the original index aPlane[-1] */
    }
    return g_aPlaneName[nSlot];
}

/* PHASE 1 cell-grid allocation, copied three times in the original (0x22E6C, 0x23E74, 0x24640).
 *
 * operator new(0x3C) is a MapCell.
 *
 * ORIGINAL BUG (0x22EF4): the store at 0x22EF4..0x22F30 writes the result of operator new whether or
 * not it succeeded, and then calls MapCell_Init on it unconditionally. MapCell_Init has no null
 * guard, so a failed allocation is a write to address zero on WinCE as well. Reproduced here rather
 * than papered over. */
static void Terrain_BuildCellGrid(MapTerrainEnv *pEnv, i32 nDimX, i32 nDimY)
{
    i32 nY;
    i32 nX;
    i32 nLayer;

    for (nY = 0; nY < PUFO_CELLS_PER_TILE * nDimY; ++nY) {
        for (nX = 0; nX < PUFO_CELLS_PER_TILE * nDimX; ++nX) {
            for (nLayer = 0; nLayer < PUFO_TERRAIN_LAYER_COUNT; ++nLayer) {
                MapCell *pCell = (MapCell *)malloc(sizeof(MapCell));

                if (pCell != NULL) {
                    MapCell_Reset(pCell);
                }
                pEnv->apCells[PUFO_TERRAIN_CELLS_PER_LAYER * nLayer
                              + PUFO_MAP_CELL_DIM * nY + nX] = pCell;
                MapCell_Init(pCell, nX, nY, nLayer);
            }
        }
    }
}

/* The stamping shape shared by three of the four module placements: the template's footprint gets
 * floor = nFloorIdx and ceiling = nCeilSpr on every level ABOVE the template's own level count,
 * running from 3 down to that count. The original guards the whole thing with `GetLevelCount <= 3`. */
static void Terrain_StampUpperLevels(MapTerrainEnv *pEnv, const MapTemplate *pTpl,
                                     i32 nTileX, i32 nTileY, u16 nFloorIdx, u16 nCeilIdx)
{
    i32 nLevels = MapTemplate_GetLevelCount(pTpl);
    i32 nRow;
    i32 nCol;
    i32 nLevel;

    if (nLevels > 3) {
        return;
    }
    for (nLevel = 3; nLevel >= nLevels; --nLevel) {
        for (nRow = 0; nRow < (i32)MapTemplate_GetHeaderByte0(pTpl); ++nRow) {
            for (nCol = 0; nCol < (i32)MapTemplate_GetHeaderByte1(pTpl); ++nCol) {
                MapCell *pCell = pEnv->apCells[PUFO_TERRAIN_CELLS_PER_LAYER * nLevel
                                               + 600 * nTileY + 60 * nRow
                                               + 10 * nTileX + nCol];
                pCell->pFloorSpr = Font_GetSprByIndex(pEnv->pFont, nFloorIdx);
                pCell->pCeilSpr  = Font_GetSprByIndex(pEnv->pFont, nCeilIdx);
            }
        }
    }
}

/* One row of a g_aTileSprIndex stamping pass: the row's four sprite slots written into the cell at
 * nIdx, plus whichever cross-cell side effect the original hangs off that pass.
 *
 *   bWallAZeroNext  slot 1 also clears the wall A of the cell to the RIGHT   (XCom-base pass 1)
 *   bWallBZeroBelow slot 2 also clears the wall B of the cell BELOW          (XCom-base pass 2)
 *   nCeilBase       slot 3 also stamps that cell's ceiling with sprite 0x14  (XCom-base pass 2)
 * A negative nCeilBase means "no extra store". */
static void Terrain_StampTileRow(MapTerrainEnv *pEnv, i32 nIdx, int nSprRow,
                                 bool bWallAZeroNext, bool bWallBZeroBelow, i32 nCeilBase)
{
    int nSlot;

    for (nSlot = 0; nSlot < 4; ++nSlot) {
        u16    nIndex = g_aTileSprIndex[nSprRow][nSlot];
        Mc1Rec *pSpr = (nIndex != 0)
                     ? Font_GetSprByIndex(pEnv->pFont, (u16)(nIndex - 1u))
                     : NULL;
        MapCell *pCell = pEnv->apCells[nIdx];

        if (nSlot == 0) {
            pCell->pFloorSpr = pSpr;
        } else if (nSlot == 1) {
            pCell->pWallSprA = pSpr;
            if (bWallAZeroNext) {
                pEnv->apCells[nIdx + 1]->pWallSprA = NULL;
            }
        } else if (nSlot == 2) {
            pCell->pWallSprB = pSpr;
            if (bWallBZeroBelow) {
                pEnv->apCells[nIdx + 60]->pWallSprB = NULL;
            }
        } else {
            pCell->pCeilSpr = pSpr;
            if (nCeilBase >= 0) {
                pEnv->apCells[nCeilBase]->pCeilSpr = Font_GetSprByIndex(pEnv->pFont, 0x14u);
            }
        }
    }
}

