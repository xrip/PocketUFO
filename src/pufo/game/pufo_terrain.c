/* pufo_terrain.c - the mission-terrain builder and its shipped tables.
 *
 * See pufo_terrain.h for the evidence. The tables are checked byte for byte against pufobeta.exe by
 * docs/parity/audit_tables.py; tools/gen_terrain_tables.py emits the four name tables from the image.
 *
 * ## How the original is shaped
 *
 * Map_BuildMissionTerrain @ 0x22e10 is 10,676 bytes and 313 blocks. It reaches everything through the
 * global Map block at 0x1139B8 and the global font block at 0x158268; the port passes both in through
 * MapTerrainEnv. Three mutually exclusive shapes follow Map_nMapLayers and Map_nMissionType, and all
 * three end in the same tail.
 *
 * Two 6x6 tile arrays live on the original's stack: a byte MODULE GRID at &pTpl.pDim1 (which overruns
 * the 20-byte CDialogTemplate it belongs to -- memset(pTpl_8, 0, 0x24) writes 36 bytes into a 20-byte
 * object) and, on the empty-layers path only, a dword KIND array at var_90. Both are indexed
 * 6 * tileY + tileX. The port keeps them as plain locals.
 *
 * The module grid means: 0 = empty, 1 = occupied by the generic terrain module, and 2/3/4 = Urban
 * module numbers 0/1/2 -- Urban re-loads a flagged cell as <terrain><value-2>. The kind array is a
 * separate per-tile classification written 0,1,2,3 over a module's 2x2 block and read by the two
 * final stamping passes, which skip kinds 1+3 and 2+3.
 *
 * ## Deviations, all of them deliberate
 *
 * - The original reuses the interior bytes of its four CDialogTemplate objects as scratch: the module
 *   name is built at pOut + 8 and the itoa buffer is at v273 + 0xC. The port uses its own buffers and
 *   four separate MapTemplate objects. Behaviour is identical; the aliasing is not load-bearing.
 * - The original indexes the cell array unchecked. The port's cell lookup bounds-checks, so a
 *   template footprint that runs past the grid is skipped rather than writing past the array.
 * - Where the original indexes a name table past its end (a mission type of 0 for the craft pad, a
 *   variant above 5 for the UFO module) the port yields an empty name, which makes the .ma1 load fail
 *   the same way a missing member does.
 */
