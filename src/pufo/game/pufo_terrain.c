/* The ceiling-break shot sweep, 0x23170..0x23DAC. Only variants 2 and 3 run it: variant 2 selects
 * object slot 18 and variant 3 selects 51, both read as *(Map + 0x108 + 4*selector).
 *
 * The two Game_RandU16(3) draws happen whether or not the shot count survives the Map_bUnk15115
 * gate, so they are not inside the `if`. */
static void Terrain_BreakCeilings(MapTerrainEnv *pEnv, const MapTemplate *pTplUfo,
                                  i32 nOffX, i32 nOffY)
{
    i32 nSelector;
    i32 nCount;
    i32 nStepX;
    i32 nStepY;
    i32 nX;
    i32 nY;
    i32 k;

    if (*pEnv->pnTerrainVariant == 2) {
        nSelector = 18;
    } else if (*pEnv->pnTerrainVariant == 3) {
        nSelector = 51;
    } else {
        nSelector = 0;
    }
    nCount = (nSelector != 0) ? (i32)Game_RandU16(0x1Eu) : 0;

    if (*pEnv->pbUnk15115 < 0x32) {
        nCount = 0;
    }

    nStepX = 1 - (i32)Game_RandU16(3u);
    nStepY = 1 - (i32)Game_RandU16(3u);
    if (nStepX + nStepY == 0) {
        nStepX = 1;
    }

    if (nCount <= 0) {
        return;
    }

    nX = PUFO_CELLS_PER_TILE * nOffX;
    nY = PUFO_CELLS_PER_TILE * nOffY;

    for (k = nCount; k != 0; --k) {
        i32 nTgtX = nX + ((i32)MapTemplate_GetHeaderByte1(pTplUfo) >> 1);
        i32 nTgtY = nY + ((i32)MapTemplate_GetHeaderByte0(pTplUfo) >> 1);
        MapGeom geom = { *pEnv->pnMapDimX, *pEnv->pnMapDimY };

        if (Map_IsValidCell(&geom, nTgtX, nTgtY, 0)) {
            *pEnv->pnShotX = nTgtX;
            *pEnv->pnShotY = nTgtY;
            if (pEnv->pfnResolveShot != NULL) {
                pEnv->pfnResolveShot(nTgtX, nTgtY, 0, 0,
                                     pEnv->apShotWeapons[nSelector], pEnv->pUser);
            }
        }
        nX += 2 * nStepX;
        nY += 2 * nStepY;
    }

    /* A second, randomised sweep. Its count is not the shot count but (Map_bUnk15115 - 30) / 10,
     * and it always uses object slot 0. Reaching it means Map_bUnk15115 >= 0x32, so the count is
     * at least 2. */
    for (k = 0; k < ((i32)*pEnv->pbUnk15115 - 30) / 10; ++k) {
        i32 nByte1 = MapTemplate_GetHeaderByte1(pTplUfo);
        i32 nByte0 = MapTemplate_GetHeaderByte0(pTplUfo);
        i32 nTgtX = (nByte1 >> 1) - (nByte1 >> 2) + (i32)Game_RandU16((u16)(nByte1 >> 1))
                  + PUFO_CELLS_PER_TILE * nOffX;
        i32 nTgtY = (nByte0 >> 1) - (nByte0 >> 2) + (i32)Game_RandU16((u16)(nByte0 >> 1))
                  + PUFO_CELLS_PER_TILE * nOffY;

        *pEnv->pnShotX = nTgtX;
        *pEnv->pnShotY = nTgtY;
        if (pEnv->pfnResolveShot != NULL) {
            pEnv->pfnResolveShot(nTgtX, nTgtY, 0, 0, pEnv->apShotWeapons[0], pEnv->pUser);
        }
    }
}

static void Terrain_BuildNormal(MapTerrainEnv *pEnv, u8 *paGrid)
{
    MapTemplate tplUfo = { 0 };
    MapTemplate tplPlane = { 0 };
    MapTemplate tplTerrain = { 0 };
    MapTemplate tplModule = { 0 };
    char   szName[64];
    u8     nType = *pEnv->pnMissionType;
    i32    nDimX = *pEnv->pnMapDimX;
    i32    nDimY = *pEnv->pnMapDimY;
    i32    nOffX = 0;
    i32    nOffY = 0;
    i32    nRow;
    i32    nCol;

    Terrain_BuildCellGrid(pEnv, nDimX, nDimY);

    /* Urban pre-marks a whole column and then a whole row, so an Urban map gets a cross of
     * special tiles before any random module is placed. */
    if (nType == PUFO_MISSION_TYPE_URBAN) {
        if (Game_RandU16(2u) == 0) {
            i32 nColPick = (i32)Game_RandU16((u16)nDimX);
            for (nRow = 0; nRow < nDimY; ++nRow) {
                paGrid[PUFO_TERRAIN_GRID_STRIDE * nRow + nColPick] = 3;
            }
        }
        if (Game_RandU16(2u) == 0) {
            i32 nRowPick = (i32)Game_RandU16((u16)nDimY);
            for (nCol = 0; nCol < nDimX; ++nCol) {
                u8 *pCell = &paGrid[PUFO_TERRAIN_GRID_STRIDE * nRowPick + nCol];
                *pCell = (*pCell == 0) ? 2 : 4;
            }
        }
    }

    /* The UFO module, loaded with nFlag 4 so its slots resolve through the font base at +8. */
    if (*pEnv->pnTerrainVariant != 0) {
        i32 nTier = *pEnv->pnTierSource;

        *pEnv->pnTier = (u8)nTier;
        pufo_strcpy(szName, Terrain_UfoName(*pEnv->pnTerrainVariant, nTier));
        MapTemplate_Load(&tplUfo, szName, 4);

        nOffX = (i32)Game_RandU16((u16)(nDimX - Terrain_Tiles(MapTemplate_GetHeaderByte1(&tplUfo))));
        nOffY = (i32)Game_RandU16((u16)(nDimY - Terrain_Tiles(MapTemplate_GetHeaderByte0(&tplUfo))));
        Terrain_StampGrid(paGrid, &tplUfo, nOffX, nOffY, 1);
    }

    /* The craft pad, loaded with nFlag 3 -- the same font base Map_PatchCraftSprites uses for the
     * craft sprites. Placement retries until the footprint lands on free grid cells. */
    MapTemplate_Load(&tplPlane, Terrain_PlaneName(nType), 3);
    for (;;) {
        *pEnv->pPlaneTileX = (u8)Game_RandU16(
            (u16)(nDimX - Terrain_Tiles(MapTemplate_GetHeaderByte1(&tplPlane))));
        *pEnv->pPlaneTileY = (u8)Game_RandU16(
            (u16)(nDimY - Terrain_Tiles(MapTemplate_GetHeaderByte0(&tplPlane))));
        if (!Terrain_FootprintBusy(paGrid, &tplPlane, *pEnv->pPlaneTileX, *pEnv->pPlaneTileY)) {
            break;
        }
    }
    Terrain_StampGrid(paGrid, &tplPlane, *pEnv->pPlaneTileX, *pEnv->pPlaneTileY, 1);

    /* The base terrain module, applied at every grid cell the placements above marked as 1. */
    Terrain_TerrainName(szName, sizeof(szName), nType);
    MapTemplate_Load(&tplTerrain, szName, 2);
    for (nRow = 0; nRow < nDimY; ++nRow) {
        for (nCol = 0; nCol < nDimX; ++nCol) {
            if (paGrid[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol] == 1) {
                Terrain_ApplyTemplate(pEnv, &tplTerrain, nCol, nRow);
            }
        }
    }

    /* Urban re-loads every specially marked cell as its own module: grid value 2/3/4 is module
     * number 0/1/2. */
    if (nType == PUFO_MISSION_TYPE_URBAN) {
        for (nRow = 0; nRow < nDimY; ++nRow) {
            for (nCol = 0; nCol < nDimX; ++nCol) {
                u8 nMark = paGrid[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol];

                if (nMark > 1) {
                    Terrain_ModuleName(szName, sizeof(szName), nType, (i32)nMark - 2);
                    MapTemplate_Load(&tplModule, szName, 2);
                    Terrain_ApplyTemplate(pEnv, &tplModule, nCol, nRow);
                    Terrain_LoadModuleRmp(pEnv, &tplModule, szName, nCol, nRow);
                }
            }
        }
    }

    if (*pEnv->pnTerrainVariant != 0) {
        Terrain_ApplyTemplate(pEnv, &tplUfo, nOffX, nOffY);
        Terrain_LoadModuleRmp(pEnv, &tplUfo, Terrain_UfoName(*pEnv->pnTerrainVariant,
                                                             *pEnv->pnTierSource),
                              nOffX, nOffY);
    }
    Terrain_ApplyTemplate(pEnv, &tplPlane, *pEnv->pPlaneTileX, *pEnv->pPlaneTileY);

    /* Random modules on every still-empty tile. This copy has only the footprint-overflow and
     * grid-collision retries -- the "not 0, not 15, not 12 on an edge" filter belongs to the
     * empty-layers path and is NOT here. */
    for (nRow = 0; nRow < nDimY; ++nRow) {
        for (nCol = 0; nCol < nDimX; ++nCol) {
            if (paGrid[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol] != 0) {
                continue;
            }
            for (;;) {
                i32 nCount = g_aTerrainModuleCount[nType];
                i32 nModule = (nType == PUFO_MISSION_TYPE_URBAN)
                            ? (i32)Game_RandU16((u16)(nCount - 3)) + 3
                            : (i32)Game_RandU16((u16)nCount);

                Terrain_ModuleName(szName, sizeof(szName), nType, nModule);
                MapTemplate_Load(&tplModule, szName, 2);
                if (Terrain_FootprintFits(&tplModule, nCol, nRow, nDimX, nDimY)
                    && !Terrain_FootprintBusy(paGrid, &tplModule, nCol, nRow)) {
                    break;
                }
            }
            Terrain_ApplyTemplate(pEnv, &tplModule, nCol, nRow);
            Terrain_LoadModuleRmp(pEnv, &tplModule, szName, nCol, nRow);
            Terrain_StampGrid(paGrid, &tplModule, nCol, nRow, 1);
        }
    }

    Terrain_BreakCeilings(pEnv, &tplUfo, nOffX, nOffY);

    MapTemplate_Free(&tplModule);
    MapTemplate_Free(&tplTerrain);
    MapTemplate_Free(&tplPlane);
    MapTemplate_Free(&tplUfo);
}

/* ------------------------------------------------------------------ the XCom base */

/* aMissionTileTypes @ 0x159D5C is 36 runtime bytes in rows of 6, laid out inside a block based at
 * 0x159768: the ARM reaches it as 0x159768 + 6 * tileRow + 0x5F4. The values the stamping guards
 * skip are 0x10, 0x11, 0x12 and 0x14; 0x14 also skips the tile's .rmp load. What each sentinel
 * means is not settled -- see docs/parity/game-core.md. */
static u8 Terrain_TileType(const MapTerrainEnv *pEnv, i32 nRow, i32 nCol)
{
    return pEnv->paTileTypes[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol];
}

static void Terrain_BuildXcomBase(MapTerrainEnv *pEnv)
{
    MapTemplate tplModule = { 0 };
    char   szName[64];
    u8     nType = *pEnv->pnMissionType;
    i32    nRow;
    i32    nCol;

    *pEnv->pnMapDimX = 6;
    *pEnv->pnMapDimY = 6;
    Terrain_BuildCellGrid(pEnv, 6, 6);

    for (nRow = 0; nRow < 6; ++nRow) {
        for (nCol = 0; nCol < 6; ++nCol) {
            u8 nTileType = Terrain_TileType(pEnv, nRow, nCol);

            char szNum[16];

            pufo_strcpy(szName, g_aTerrainNameByMission[nType]);
            snprintf(szNum, sizeof szNum, "%d", nTileType);
            pufo_strcat(szName, szNum, sizeof szName);
            MapTemplate_Load(&tplModule, szName, 2);
            Terrain_ApplyTemplate(pEnv, &tplModule, nCol, nRow);
            Terrain_StampUpperLevels(pEnv, &tplModule, nCol, nRow, 2u, 3u);

            if (nTileType != 0x14) {
                Terrain_LoadModuleRmp(pEnv, &tplModule, szName, nCol, nRow);
            }
        }
    }

    /* Stamping pass 1: walks g_aTileSprIndex rows 4..7 and guards on the tile type and the tile
     * one COLUMN to the right. Cell index 189 + 600*tileRow + 60*k + 10*tileCol, that is
     * y = 3 + k + 10*tileRow, x = 9 + 10*tileCol. */
    for (nRow = 0; nRow < 6; ++nRow) {
        for (nCol = 0; nCol < 5; ++nCol) {
            u8 nTile = Terrain_TileType(pEnv, nRow, nCol);

            if (nTile == 0x14 || Terrain_TileType(pEnv, nRow, nCol + 1) == 0x14
                || nTile == 0x10 || nTile == 0x12) {
                continue;
            }
            for (i32 k = 0; k < 4; ++k) {
                Terrain_StampTileRow(pEnv, 189 + 600 * nRow + 60 * k + 10 * nCol,
                                     4 + k, k < 3, false, -1);
            }
        }
    }

    /* Stamping pass 2: rows 0..3, guarded on the tile type and the tile one ROW below. Cell index
     * 543 + 600*tileRow + 10*tileCol + j, that is y = 9 + 10*tileRow, x = 3 + j + 10*tileCol. */
    for (nRow = 0; nRow < 5; ++nRow) {
        for (nCol = 0; nCol < 6; ++nCol) {
            u8 nTile = Terrain_TileType(pEnv, nRow, nCol);

            if (nTile == 0x14 || Terrain_TileType(pEnv, nRow + 1, nCol) == 0x14
                || nTile == 0x10 || nTile == 0x11) {
                continue;
            }
            for (i32 j = 0; j < 4; ++j) {
                Terrain_StampTileRow(pEnv, 543 + 600 * nRow + 10 * nCol + j,
                                     j, false, j < 3,
                                     (j == 0) ? 543 + 600 * nRow + 10 * nCol : -1);
            }
        }
    }

    MapTemplate_Free(&tplModule);
}

/* ------------------------------------------------------------------ the empty-layers fallback */

/* The two final stamping passes key on the dword KIND array rather than on aMissionTileTypes, and
 * both read the kind at (row, col + 1): pass A walks the array from its start and reads +4, pass B
 * starts one dword in and reads +0. */
static void Terrain_StampKindPassA(MapTerrainEnv *pEnv, const i32 *paKind,
                                   i32 nDimX, i32 nDimY)
{
    i32 nRow;
    i32 nCol;

    for (nRow = 0; nRow < nDimY; ++nRow) {
        for (nCol = 0; nCol < nDimX - 1; ++nCol) {
            i32 nKind = paKind[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol + 1];

            if (nKind == 1 || nKind == 3) {
                continue;
            }
            for (i32 nn = 0; nn < 4; ++nn) {
                i32 nIdx = 189 + 600 * nRow + 60 * nn + 10 * nCol;
                int nSlot;

                for (nSlot = 0; nSlot < 4; ++nSlot) {
                    u16    nIndex = g_aTileSprIndex[12 + nn][nSlot];
                    Mc1Rec *pSpr = (nIndex != 0)
                                 ? Font_GetSprByIndex(pEnv->pFont, (u16)(nIndex - 1u))
                                 : NULL;
                    MapCell *pCell = pEnv->apCells[nIdx];

                    if (nSlot == 0) {
                        pCell->pFloorSpr = pSpr;
                    } else if (nSlot == 1) {
                        pCell->pWallSprA = pSpr;
                        if (nn < 3) {
                            pEnv->apCells[nIdx + 1]->pWallSprA = NULL;
                        }
                        if (nn == 0) {
                            pEnv->apCells[190 + 600 * nRow + 10 * nCol]->pWallSprA =
                                Font_GetSprByIndex(pEnv->pFont, 0x58u);
                        }
                    } else if (nSlot == 2) {
                        pCell->pWallSprB = pSpr;
                    } else {
                        pCell->pCeilSpr = pSpr;
                    }
                }
            }
        }
    }
}

static void Terrain_StampKindPassB(MapTerrainEnv *pEnv, const i32 *paKind,
                                   i32 nDimX, i32 nDimY)
{
    i32 nRow;
    i32 nCol;

    for (nRow = 0; nRow < nDimY - 1; ++nRow) {
        for (nCol = 0; nCol < nDimX; ++nCol) {
            i32 nKind = paKind[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol + 1];

            if (nKind == 2 || nKind == 3) {
                continue;
            }
            for (i32 i1 = 0; i1 < 4; ++i1) {
                i32 nIdx = 543 + 600 * nRow + 10 * nCol + i1;
                int nSlot;

                for (nSlot = 0; nSlot < 4; ++nSlot) {
                    u16    nIndex = g_aTileSprIndex[8 + i1][nSlot];
                    Mc1Rec *pSpr = (nIndex != 0)
                                 ? Font_GetSprByIndex(pEnv->pFont, (u16)(nIndex - 1u))
                                 : NULL;
                    MapCell *pCell = pEnv->apCells[nIdx];

                    if (nSlot == 0) {
                        pCell->pFloorSpr = pSpr;
                    } else if (nSlot == 1) {
                        pCell->pWallSprA = pSpr;
                    } else if (nSlot == 2) {
                        pCell->pWallSprB = pSpr;
                        if (i1 < 3) {
                            pEnv->apCells[nIdx + 60]->pWallSprB = NULL;
                        }
                    } else {
                        pCell->pCeilSpr = pSpr;
                        if (i1 == 0) {
                            pEnv->apCells[543 + 600 * nRow + 10 * nCol]->pCeilSpr =
                                Font_GetSprByIndex(pEnv->pFont, 0x58u);
                        }
                    }
                }
            }
        }
    }
}

static void Terrain_BuildEmptyLayers(MapTerrainEnv *pEnv, u8 *paGrid, i32 *paKind)
{
    MapTemplate tplModule = { 0 };
    char   szName[64];
    u8     nType = *pEnv->pnMissionType;
    i32    nDimX = 6;
    i32    nDimY = 6;
    i32    nRow;
    i32    nCol;

    *pEnv->pnMapDimX = 6;
    *pEnv->pnMapDimY = 6;
    memset(paKind, 0, PUFO_TERRAIN_GRID_CELLS * sizeof(i32));
    Terrain_BuildCellGrid(pEnv, nDimX, nDimY);

    /* Three fixed tiles along the bottom row, all from one template: <terrain> + "4". The "4" is
     * the literal pDefault @ 0xAAD4C, not the per-mission-type suffix table -- so even a jungle
     * fallback loads <terrain>4.ma1. */
    pufo_strcpy(szName, g_aTerrainNameByMission[nType]);
    pufo_strcat(szName, "4", sizeof(szName));
    MapTemplate_Load(&tplModule, szName, 2);
    Terrain_ApplyTemplate(pEnv, &tplModule, 5, 5);
    Terrain_ApplyTemplate(pEnv, &tplModule, 4, 5);
    Terrain_ApplyTemplate(pEnv, &tplModule, 3, 5);
    paGrid[33] = 1;
    paGrid[34] = 1;
    paGrid[35] = 1;

    /* Cell index 3050 + 3600*level + 60*row + col is y = 50 + row, x = 50 + col; the same floor
     * and ceiling are stamped at x - 10 and x - 20 as well. */
    {
        i32 nLevels = MapTemplate_GetLevelCount(&tplModule);
        i32 nLevel;

        if (nLevels <= 3) {
            for (nLevel = 3; nLevel >= nLevels; --nLevel) {
                for (nRow = 0; nRow < (i32)MapTemplate_GetHeaderByte0(&tplModule); ++nRow) {
                    for (nCol = 0; nCol < (i32)MapTemplate_GetHeaderByte1(&tplModule); ++nCol) {
                        i32 nBase = 3050 + PUFO_TERRAIN_CELLS_PER_LAYER * nLevel + 60 * nRow + nCol;
                        int nShift;

                        for (nShift = 0; nShift < 3; ++nShift) {
                            MapCell *pCell = pEnv->apCells[nBase - 10 * nShift];
                            pCell->pFloorSpr = Font_GetSprByIndex(pEnv->pFont, 0x3Fu);
                            pCell->pCeilSpr  = Font_GetSprByIndex(pEnv->pFont, 0x3Eu);
                        }
                    }
                }
            }
        }
    }

    Terrain_LoadModuleRmp(pEnv, &tplModule, szName, 5, 5);
    Terrain_LoadModuleRmp(pEnv, &tplModule, szName, 4, 5);
    Terrain_LoadModuleRmp(pEnv, &tplModule, szName, 3, 5);

    /* One random module tile, marked in both arrays. */
    pufo_strcpy(szName, g_aTerrainNameByMission[nType]);
    pufo_strcat(szName, (*pEnv->pbSpawnAlt != 0) ? "15" : "0", sizeof(szName));
    MapTemplate_Load(&tplModule, szName, 2);
    *pEnv->pnSpawnTileX = (i32)Game_RandU16(5u);
    *pEnv->pnSpawnTileY = (i32)Game_RandU16(4u);
    Terrain_ApplyTemplate(pEnv, &tplModule, *pEnv->pnSpawnTileX, *pEnv->pnSpawnTileY);
    Terrain_StampUpperLevels(pEnv, &tplModule, *pEnv->pnSpawnTileX, *pEnv->pnSpawnTileY,
                             0x3Fu, 0x3Eu);

    {
        i32 nBase = PUFO_TERRAIN_GRID_STRIDE * *pEnv->pnSpawnTileY + *pEnv->pnSpawnTileX;

        paGrid[nBase] = 1;
        paGrid[nBase + 1] = 1;
        paGrid[nBase + PUFO_TERRAIN_GRID_STRIDE] = 1;
        paGrid[nBase + PUFO_TERRAIN_GRID_STRIDE + 1] = 1;
        paKind[nBase] = 0;
        paKind[nBase + 1] = 1;
        paKind[nBase + PUFO_TERRAIN_GRID_STRIDE] = 2;
        paKind[nBase + PUFO_TERRAIN_GRID_STRIDE + 1] = 3;
    }
    Terrain_LoadModuleRmp(pEnv, &tplModule, szName, *pEnv->pnSpawnTileX, *pEnv->pnSpawnTileY);

    /* Random modules. This copy adds the filters the normal path does not have: never module 4,
     * never 0, never 15, and never 12 on a map edge. */
    for (nRow = 0; nRow < nDimY; ++nRow) {
        for (nCol = 0; nCol < nDimX; ++nCol) {
            if (paGrid[PUFO_TERRAIN_GRID_STRIDE * nRow + nCol] != 0) {
                continue;
            }
            for (;;) {
                i32 nModule;

                do {
                    nModule = (i32)Game_RandU16((u16)g_aTerrainModuleCount[nType]);
                } while (nModule == 4);

                if (nModule != 0 && nModule != 15
                    && (nModule != 12
                        || (nCol != 0 && nCol != nDimX - 1
                            && nRow != 0 && nRow != nDimY - 1))) {
                    Terrain_ModuleName(szName, sizeof(szName), nType, nModule);
                    MapTemplate_Load(&tplModule, szName, 2);
                    if (Terrain_FootprintFits(&tplModule, nCol, nRow, nDimX, nDimY)
                        && !Terrain_FootprintBusy(paGrid, &tplModule, nCol, nRow)) {
                        break;
                    }
                }
            }
            Terrain_ApplyTemplate(pEnv, &tplModule, nCol, nRow);
            Terrain_StampUpperLevels(pEnv, &tplModule, nCol, nRow, 0x3Fu, 0x3Eu);
            Terrain_LoadModuleRmp(pEnv, &tplModule, szName, nCol, nRow);
            Terrain_StampGrid(paGrid, &tplModule, nCol, nRow, 1);

            if (MapTemplate_GetHeaderByte1(&tplModule) > 10) {
                i32 nBase = PUFO_TERRAIN_GRID_STRIDE * nRow + nCol;
                paKind[nBase + 1] = 1;
                paKind[nBase + PUFO_TERRAIN_GRID_STRIDE] = 2;
                paKind[nBase + PUFO_TERRAIN_GRID_STRIDE + 1] = 3;
                paKind[nBase] = 0;
            }
        }
    }

    Terrain_StampKindPassA(pEnv, paKind, nDimX, nDimY);
    Terrain_StampKindPassB(pEnv, paKind, nDimX, nDimY);

    MapTemplate_Free(&tplModule);
}

/* ------------------------------------------------------------------ the tail */

/* Clear bits 3..6 of every cell's nFlags32 (the mask is 0xFFFFFF87, which KEEPS bits 0, 1, 2 and 7).
 * No null test, exactly as the original has it at 0x25764 -- a cell the allocator failed to produce
 * is a crash here too.
 *
 * Worth stating because it looks stronger than it is: MapCell_Init already masks with 0xFFFFFF80,
 * which clears bits 0..6. On a freshly built grid this tail is therefore a no-op, and it only
 * matters for a cell whose flags were set between allocation and the tail.
 *
 * ORIGINAL BUG (0x25740): the cell pointer is loaded and immediately written through with no null
 * test, so one cell the allocator failed to produce is a crash. */
static void Terrain_ClearCellFlags(MapTerrainEnv *pEnv)
{
    i32 nDimX = *pEnv->pnMapDimX;
    i32 nDimY = *pEnv->pnMapDimY;
    i32 nY;
    i32 nX;
    i32 nLayer;

    for (nY = 0; nY < PUFO_CELLS_PER_TILE * nDimY; ++nY) {
        for (nX = 0; nX < PUFO_CELLS_PER_TILE * nDimX; ++nX) {
            for (nLayer = 0; nLayer < PUFO_TERRAIN_LAYER_COUNT; ++nLayer) {
                MapCell *pCell = pEnv->apCells[PUFO_TERRAIN_CELLS_PER_LAYER * nLayer
                                               + PUFO_MAP_CELL_DIM * nY + nX];
                pCell->nFlags32 &= 0xFFFFFF87u;
            }
        }
    }
}

/* ------------------------------------------------------------------ Map_BuildMissionTerrain */

void Map_BuildMissionTerrain(MapTerrainEnv *pEnv)
{
    u8  aGrid[PUFO_TERRAIN_GRID_CELLS];
    i32 aKind[PUFO_TERRAIN_GRID_CELLS];

    memset(aGrid, 0, sizeof(aGrid));
    memset(aKind, 0, sizeof(aKind));

    if (pEnv->pfnLoadTactSprites != NULL) {
        pEnv->pfnLoadTactSprites(pEnv->pUser);
    }

    if (*pEnv->pnMapLayers != 0) {
        Terrain_BuildNormal(pEnv, aGrid);
    } else if (*pEnv->pnMissionType == PUFO_MISSION_TYPE_XCOM_BASE) {
        Terrain_BuildXcomBase(pEnv);
    } else {
        Terrain_BuildEmptyLayers(pEnv, aGrid, aKind);
    }

    Terrain_ClearCellFlags(pEnv);

    {
        CraftSpritePatchEnv craft = {
            pEnv->nCraftSprBase, pEnv->apCells, *pEnv->pnMapLayers,
            *pEnv->pPlaneTileX, *pEnv->pPlaneTileY
        };
        Map_PatchCraftSprites(pEnv->pFont, &craft);
    }
}
