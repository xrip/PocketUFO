#!/usr/bin/env python3
"""coverage.py - map original IDB functions to recreated code.

Reads docs/idb/functions.tsv (the full function inventory) and reports, per name
prefix, how many original functions have a matching definition in src/pufo. The
output is the working form of the parity report required by the goal: every
original function is either matched, listed as a helper that needs no port, or
listed as a gap.

Run:  python tools/coverage.py [--md out.md]
"""
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "docs", "idb", "functions.tsv")
SRC = os.path.join(ROOT, "src", "pufo")

# Names that are compiler or library artifacts in the original image, not game
# behaviour: they need no recreated counterpart.
SKIP_RE = re.compile(
    r"^(nullsub_|sub_|j_|locret_|__|_\w+$|"
    r"(operator|__aeabi|__rt_|_Cxx|std::))"
)


def load_functions():
    rows = []
    with open(TSV, encoding="utf-8") as f:
        header = f.readline()
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3:
                continue
            rows.append((parts[0], parts[1], int(parts[2])))
    return rows


def load_source_names():
    """Every identifier defined or declared in src/pufo."""
    names = set()
    for dirpath, _dirs, files in os.walk(SRC):
        for name in files:
            if not name.endswith((".c", ".h")):
                continue
            with open(os.path.join(dirpath, name), encoding="utf-8", errors="replace") as f:
                for line in f:
                    for word in re.findall(r"[A-Za-z_][A-Za-z0-9_]{3,}", line):
                        names.add(word)
    return names


def prefix_of(name):
    m = re.match(r"^([A-Z][a-z]+[A-Za-z]*)_", name)
    return m.group(1) if m else "(other)"


def main():
    as_md = None
    if "--md" in sys.argv:
        as_md = sys.argv[sys.argv.index("--md") + 1]

    funcs = load_functions()
    src_names = load_source_names()

    groups = defaultdict(lambda: [0, 0, []])
    matched, skipped, gaps = [], [], []

    for addr, name, size in funcs:
        hit = name in src_names
        g = groups[prefix_of(name)]
        if SKIP_RE.match(name):
            skipped.append(name)
            continue
        if hit:
            matched.append((addr, name, size))
            g[0] += 1
        else:
            gaps.append((addr, name, size))
            g[1] += 1

    lines = []
    lines.append("# Parity coverage: original functions to recreated code")
    lines.append("")
    lines.append("Generated by `tools/coverage.py`. Source of truth: "
                 "`docs/idb/functions.tsv` (every function in `pufobeta.exe.i64`) "
                 "matched against definitions in `src/pufo`.")
    lines.append("")
    total = len(matched) + len(gaps)
    lines.append("| original functions | need a port | recreated | not recreated | library/compiler artifacts |")
    lines.append("|---|---|---|---|---|")
    lines.append("| %d | %d | %d | %d | %d |"
                 % (len(funcs), total, len(matched), len(gaps), len(skipped)))
    lines.append("")
    lines.append("## Coverage by subsystem prefix")
    lines.append("")
    lines.append("| prefix | recreated | not recreated |")
    lines.append("|---|---|---|")
    for pre in sorted(groups, key=lambda p: -(groups[p][0] + groups[p][1])):
        done, todo, _ = groups[pre]
        if done + todo == 0:
            continue
        lines.append("| `%s` | %d | %d |" % (pre, done, todo))
    lines.append("")
    lines.append("## Recreated (matched by name)")
    lines.append("")
    for addr, name, size in sorted(matched, key=lambda r: r[1]):
        lines.append("- `%s` @ `%s` (%d bytes)" % (name, addr, size))
    lines.append("")
    lines.append("## Not recreated yet")
    lines.append("")
    for addr, name, size in sorted(gaps, key=lambda r: -r[2]):
        lines.append("- `%s` @ `%s` (%d bytes)" % (name, addr, size))
    lines.append("")
    out = "\n".join(lines) + "\n"

    if as_md:
        with open(as_md, "w", encoding="utf-8") as f:
            f.write(out)
        print("wrote %s" % as_md)
    print("%d functions, %d recreated, %d gaps, %d artifacts"
          % (len(funcs), len(matched), len(gaps), len(skipped)))


if __name__ == "__main__":
    main()
