#!/usr/bin/env python3
"""Generate the lang.dat TEXTS table header.

Usage (run from outside the data directory, with -I, and pass the paths as arguments):
    python3 -I tools/gen_texts_lang.py E:/pocketufo/lang.dat E:/pocketufo/src/pufo/asset/pufo_texts_lang.h

The output is the 1650 text records of lang.dat's TEXTS.DAT, one C string per record, in record
order, as \\xNN escapes of the raw cp1251 bytes so the header stays plain ASCII in any encoding.
tools/check.sh runs this and fails when the committed header no longer matches lang.dat.
"""

import struct
import sys

REC_FILE = 200   # the stride inside TEXTS.DAT
REC_RAM = 205    # the stride Assets_LoadStartup uses in RAM (5 bytes of slack per record)


def texts_blob(path):
    data = open(path, "rb").read()
    count = struct.unpack_from("<I", data, 0)[0]
    for i in range(count):
        off = 4 + 21 * i
        name = data[off:off + 13].split(b"\0")[0].decode("ascii", "replace")
        size, foff = struct.unpack_from("<II", data, off + 13)
        if name.upper() == "TEXTS.DAT":
            return data[foff:foff + size]
    raise SystemExit("%s: no TEXTS.DAT entry" % path)


_HEX_DIGITS = set("0123456789abcdefABCDEF")


def c_string(raw):
    """One record's terminator-terminated bytes as ONE C string literal, ASCII-only.

    A \\xNN escape swallows a following hex digit, so a printable hex digit right after an escape
    is escaped too. Adjacent literals instead of one literal is -Werror,-Wstring-concatenation in
    an array initializer, so the table is never split that way.
    """
    body = raw.split(b"\0", 1)[0]
    out = []
    after_escape = False
    for byte in body:
        if byte == 0x22:
            out.append('\\"')
            after_escape = False
        elif byte == 0x5C:
            out.append("\\\\")
            after_escape = False
        elif 0x20 <= byte < 0x7F and not (after_escape and chr(byte) in _HEX_DIGITS):
            out.append(chr(byte))
            after_escape = False
        else:
            out.append("\\x%02X" % byte)
            after_escape = True
    return '"' + "".join(out) + '"'


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    lang_path, out_path = sys.argv[1], sys.argv[2]

    blob = texts_blob(lang_path)
    body, header = blob[2:], blob[:2]
    n_rec = len(body) // REC_FILE

    lines = []
    lines.append("/* Generated by tools/gen_texts_lang.py -- do not edit by hand.")
    lines.append(" * Regenerate: python3 -I tools/gen_texts_lang.py <lang.dat> src/pufo/asset/pufo_texts_lang.h")
    lines.append(" *")
    lines.append(" * lang.dat TEXTS.DAT: %d bytes = a 2-byte header (%02X %02X) then %d records of %d bytes,"
                 % (len(blob), header[0], header[1], n_rec, REC_FILE))
    lines.append(" * every one terminated inside its record. Assets_LoadStartup @ 0x384E0..0x38564 reads the")
    lines.append(" * header into the TEXTS block at 0xB38D0 and then copies each record into a %d-byte slot" % REC_RAM)
    lines.append(" * (5 bytes of slack in RAM), which is why every fixed label address in the binary is")
    lines.append(" * 0xB38D0 + %d * record: BaseInfoScreen_BuildPanels' captions are records 1623..1645," % REC_RAM)
    lines.append(" * Ship_FormatDisplayName's craft names are 137..139/418/419, the radar messages 1599..1603.")
    lines.append(" *")
    lines.append(" * The reader scans archive 0 before archive 1 (pufo_asset.h), and archive 0 is lang.dat, so")
    lines.append(" * this is the text the shipped build shows: main.dat also carries a TEXTS.DAT (1721 records,")
    lines.append(" * English) and it never loads. Strings are the raw cp1251 bytes the font renders, escaped as")
    lines.append(" * \\xNN so this file is plain ASCII. \"\" is a record lang.dat leaves empty -- %d of the %d."
                 % (sum(1 for i in range(n_rec)
                        if not body[i * REC_FILE:(i + 1) * REC_FILE].split(b"\0", 1)[0]), n_rec))
    lines.append(" */")
    lines.append("#ifndef PUFO_TEXTS_LANG_H")
    lines.append("#define PUFO_TEXTS_LANG_H")
    lines.append("")
    lines.append("#define PUFO_TEXT_LANG_COUNT %d" % n_rec)
    lines.append("")
    lines.append("/* Record n here is (const char *)pTextRecs + PUFO_TEXT_REC_STRIDE * n after the boot load. */")
    lines.append("static const char *const g_apzTextsLang[PUFO_TEXT_LANG_COUNT] = {")
    for i in range(n_rec):
        raw = body[i * REC_FILE:(i + 1) * REC_FILE]
        lines.append("    %s,  /* %d */" % (c_string(raw), i))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* PUFO_TEXTS_LANG_H */")

    open(out_path, "wb").write(("\n".join(lines) + "\n").encode("ascii"))
    print("%s: %d records -> %s" % (lang_path, n_rec, out_path))


if __name__ == "__main__":
    main()
